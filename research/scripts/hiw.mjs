import { chromium } from 'playwright';
const b=await chromium.launch(); const p=await (await b.newContext({viewport:{width:1440,height:900}})).newPage();
await p.goto('https://puppy.instabizweb.com/how-it-works',{waitUntil:'networkidle'}); await p.waitForTimeout(1500);
await p.getByRole('tab',{name:/Imported/}).click(); await p.waitForTimeout(1200);
await p.evaluate(()=>window.scrollTo(0,350)); await p.waitForTimeout(900);
await p.screenshot({path:'../screenshots/how-it-works-imported-tab-1440.png'});
await p.goto('https://puppy.instabizweb.com/faq',{waitUntil:'networkidle'}); await p.waitForTimeout(1200);
await p.locator('input[type=search]').fill('korea'); await p.waitForTimeout(900);
await p.screenshot({path:'../screenshots/faq-search-korea-1440.png'});
console.log(await p.evaluate(()=>document.querySelector('.tp-notes__count').innerText+' | '+[...document.querySelectorAll('.tp-note')].length+' | '+location.search));
